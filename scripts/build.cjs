const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
const read = file => fs.readFileSync(path.join(root, file), 'utf8');
const source = read('source.html');
const app = [...source.matchAll(/<script\b[^>]*>([\s\S]*?)<\/script>/g)].map(m => m[1]).find(s => s.includes('var PLANS ='));
if (!app) throw new Error('Domain source missing');
const prefix = app.slice(0, app.indexOf('// ================================================================ icons:'));
fs.mkdirSync(path.join(root, 'lib'), { recursive: true });
fs.writeFileSync(path.join(root, 'lib/domain.cjs'), 'module.exports = ' + prefix + 'return {CASES,EVALS,MEMBERS,SCHEMA,SYSTEM_PROMPT,sourcesFor,sampleFor};\n})();');
let html = source.replace(/<script>\s*\/\* PFAI-HELPER-START[\s\S]*?\/\* PFAI-HELPER-END \*\/\s*<\/script>/, '<script src="/connection.js"></script>');
if (html === source) throw new Error('Original connection helper was not replaced');
html = html.replace('PFAI.generate({ system:', 'PFAI.generate({ caseKey: c.key, system:');
html = html.replace('Live: results come from AI using the connected key', 'Live AI · owner-funded · synthetic cases');
html = html.replace('>Use real AI</button>', '>Open live demo</button>');
html = html.replace('if (PITCH) document.querySelectorAll', 'if (false) document.querySelectorAll');
html = html.replace('Nothing is routed or sent.', 'Reviewer actions stay in this browser visit; nothing is routed. Live mode sends only built-in synthetic case evidence to Claude.');
html = html.replace('Synthetic decision support:', 'Synthetic demo · reviewer actions and eval verdicts reset on page reload. Synthetic decision support:');
fs.mkdirSync(path.join(root, 'public'), { recursive: true });
fs.writeFileSync(path.join(root, 'public/index.html'), html);
fs.writeFileSync(path.join(root, 'public/connection.js'), read('scripts/client-adapter.js'));
console.log('Built hosted UI and server domain from corrected source. No credentials included.');
